    /**
     * Resolves the full Surah stream URL for any of the 114 Surahs with 3-digit padding (e.g. 001.mp3, 114.mp3).
     */
    fun getFullSurahStreamUrl(reciterServerUrl: String, surahNumber: Int): String {
        val padded = String.format(Locale.US, "%03d.mp3", surahNumber)
        val base = if (reciterServerUrl.endsWith("/")) reciterServerUrl else "$reciterServerUrl/"
        return "$base$padded"
    }

    fun getSurahByNumber(number: Int): QuranSurah? {
