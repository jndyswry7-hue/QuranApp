    fun extractWordsForTracker(surah: QuranSurah): List<String> {
        val clean = surah.sampleAyahText
            .replace("۝", " ")
            .replace("۞", " ")
            .replace("۩", " ")
            .replace("ۛ", "")
            .replace("ۖ", "")
            .replace("ۗ", "")
            .replace("ۚ", "")
            .replace("ۙ", "")
            .replace("ۘ", "")
            .replace("ۜ", "")
        return clean.split("\\s+".toRegex()).filter { it.isNotBlank() }
    }

    /**
     * Strips Arabic diacritics / Tashkeel for matching.
     */
    fun stripTashkeel(text: String): String {
        return text
            .replace("[\u064B-\u065F\u0670]".toRegex(), "")
            .replace("ٱ", "ا")
            .replace("أ", "ا")
            .replace("إ", "ا")
            .replace("آ", "ا")
            .replace("ى", "ي")
            .replace("ة", "ه")
    }
